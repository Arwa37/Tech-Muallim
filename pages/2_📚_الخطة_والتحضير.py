import streamlit as st

st.title("📚 الخطة والتحضير الذكي")
st.markdown("---")

current_book = st.session_state.get('selected_book', 'لم يتم اختيار مقرر بعد (يرجى اختياره من الرئيسية)')
st.info(f"📖 المقرر الحالي: **{current_book}**")

unit_name = st.selectbox("اختر الوحدة الدراسية:",
                         ["الوحدة الأولى: الميكانيكا والحرارة", "الوحدة الثانية: الكهرباء والمغناطيسية",
                          "الوحدة الثالثة: الموجات والضوء"])
lesson_name = st.text_input("عنوان الدرس:", "مثال: قانون نيوتن الثاني وحركة الأجسام")

if st.button("🚀 توليد ملخص الدرس وأهداف بلوم"):
    st.markdown("### 📝 ملخص الدرس وأهم النقاط")
    st.success("هنا يعرض المودل تلخيصاً شاملاً لأهم مفاهيم الدرس والقوانين الفيزيائية المرتبطة به.")

    st.markdown("### 🎯 أهداف بلوم التعليمية")
    st.write("- **الهدف المعرفي (المستوى الفكري):** أن يتعرف الطالب على صيغة القانون الرياضية ويشرح وحدات القياس.")
    st.write("- **الهدف التطبيقي (المستوى المهاري/العملي):** أن يحل الطالب مسائل حسابية تطبيقية على القانون بدقة.")

st.markdown("---")
st.subheader("📅 خطة الحصص الثلاث الموزعة")
col1, col2, col3 = st.columns(3)

with col1:
    st.markdown("#### الحصة الأولى")
    st.write("المفاهيم الأساسية، المقدمة الاستهلالية، والمناقشة.")
with col2:
    st.markdown("#### الحصة الثانية")
    st.write("التطبيق العملي، المسائل الحسابية، وربطها بالتجارب.")
with col3:
    st.markdown("#### الحصة الثالثة")
    st.write("التقييم التكويني، الأنشطة التمايزية، وغلق الدرس.")

if st.button("📥 تصدير الخطة كملف Word (.docx)"):
    st.success("تم تجهيز ملف خطة الدرس للتحميل الفوري!")